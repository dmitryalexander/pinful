const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync(require('node:path').join(__dirname, '../static/modern.js'), 'utf8');
const wall = {children: [], replaceChildren(...items) {this.children = items;}, append(...items) {this.children.push(...items);}};
const more = {getBoundingClientRect: () => ({top: 5000})};
const items = Array.from({length:105}, (_,i) => ({id:String(i+1)}));
const context = {wall, more, status:{}, validPinId:()=>true, cardFor:i=>i, refresh(){}, clearTimeout(){}, setTimeout(){}, innerHeight:800, items};
vm.createContext(context);
vm.runInContext(source.slice(source.indexOf(' const HIST_STEP='), source.indexOf(' function nameDialog')), context);
vm.runInContext('showHistory(items)', context);
assert.equal(wall.children.length,40);
vm.runInContext('histMore()',context);
assert.equal(wall.children.length,80);
vm.runInContext('histMore()',context);
assert.equal(wall.children.length,105);
assert.equal(new Set(wall.children.map(i=>i.id)).size,105);
assert.equal(more.hidden,true);
vm.runInContext('showHistory([...items].reverse())',context);
assert.equal(wall.children.length,40);
assert.equal(wall.children[0].id,'105');
assert.equal(more.hidden,false);
vm.runInContext('showHistory([])',context);
assert.equal(wall.children.length,0);
assert.equal(more.hidden,true);
assert.match(source, /active.items=shuffle\(active.items\)/);
assert.match(source, /showHistory\(d.lists.find\(l=>l.id===d.activeId\).items\)/);
console.log('PASS: saved lists load progressively, reset after full-list reorder, and terminate without duplicates.');
